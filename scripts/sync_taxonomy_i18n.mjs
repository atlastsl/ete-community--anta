const taxonomyFr = {
  categories: categoriesFr,
  domains: Object.fromEntries(PRODUCTION_DOMAINS.map((d) => [d, DOMAIN_FR[d]])),
  subdomains: Object.fromEntries(allSubs.map((s) => [s, SUBDOMAIN_FR[s] ?? titleEn(s)])),
}

const taxonomyEn = {
  categories: categoriesEn,
  domains: Object.fromEntries(PRODUCTION_DOMAINS.map((d) => [d, DOMAIN_EN[d]])),
  subdomains: Object.fromEntries(allSubs.map((s) => [s, titleEn(s)])),
}

function patchLocale(path, taxonomy) {
  const data = JSON.parse(readFileSync(path, 'utf8'))
  data.taxonomy = taxonomy
  writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`, 'utf8')
}

patchLocale('inertia/locales/admin/fr.json', taxonomyFr)
patchLocale('inertia/locales/public/fr.json', taxonomyFr)
patchLocale('inertia/locales/admin/en.json', taxonomyEn)
patchLocale('inertia/locales/public/en.json', taxonomyEn)

